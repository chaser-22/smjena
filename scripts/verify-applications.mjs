import assert from 'node:assert/strict';

// Only the disposable migration runner calls this. Never connect to production.
export async function verifyApplications(db, { employerId, employerUserId, workerOneId, workerTwoId, workerThreeId }) {
  const actor = async (id, role = 'authenticated') => {
    await db.exec('reset role');
    await db.query("select set_config('request.jwt.claim.sub',$1,false)", [id ?? '']);
    if (role === 'anon' || role === 'authenticated') await db.exec(`set role ${role}`);
  };
  let serial = 0;
  const publish = async (overrides = {}) => {
    const value = { key: `90000000-0000-4000-8000-${String(++serial).padStart(12, '0')}`, name: 'Pilot Hotel', area: 'Centar', address: 'Private road 42', start: new Date(Date.now() + 20 * 86400000).toISOString(), ...overrides };
    const end = new Date(Date.parse(value.start) + 6 * 3600000).toISOString();
    return (await db.query(`select public.publish_application_shift($1,$2,$3,'Konobar',$4,$5,$6,$7,8000,1::smallint,'{}'::text[],true) as id`,
      [employerId, value.key, value.name, value.area, value.address, value.start, end])).rows[0].id;
  };
  const apply = async (id) => (await db.query('select public.apply_to_shift($1) as id', [id])).rows[0].id;
  const transition = async (id, decision) => (await db.query('select public.transition_application($1,$2) as status', [id, decision])).rows[0].status;
  const contact = async (id) => (await db.query('select * from public.application_contact($1)', [id])).rows;
  await actor(employerUserId);
  await assert.rejects(() => publish(), /Pilot not enabled/);
  await assert.rejects(() => db.query('insert into private.application_pilot_workspaces(employer_id,enabled) values($1,true)', [employerId]), /permission denied/);
  await actor(employerUserId, 'owner');
  await db.query('insert into private.application_pilot_workspaces(employer_id,enabled) values($1,true)', [employerId]);
  await actor(employerUserId);
  const shift = await publish({ key: '90000000-0000-4000-8000-000000000010' });
  assert.equal(await publish({ key: '90000000-0000-4000-8000-000000000010' }), shift);
  await assert.rejects(() => publish({ name: 'Contact +38267123456' }), /Invalid public/);
  await assert.rejects(() => publish({ area: 'Private road 42' }), /Invalid public/);
  await assert.rejects(() => db.query('select public.raise_shift_pay($1,1000)', [shift]), /not enabled/);
  await assert.rejects(() => db.query('select public.cancel_shift($1)', [shift]), /not enabled/);
  await actor(null, 'anon');
  const publicRows = (await db.query('select * from public.public_shift_listings where shift_id=$1', [shift])).rows;
  assert.equal(publicRows.length, 1);
  assert.equal(JSON.stringify(publicRows).includes('Private road'), false);
  for (const table of ['application_posts', 'shift_applications', 'application_inbox', 'shift_locations']) {
    await assert.rejects(() => db.query(`select * from public.${table}`), /permission denied/);
  }
  await assert.rejects(() => apply(shift), /permission denied/);

  await actor(workerOneId);
  const one = await apply(shift);
  assert.equal(await apply(shift), one);
  assert.deepEqual(await contact(one), []);
  await assert.rejects(() => transition(one, 'accept'), /Invalid application state/);
  await assert.rejects(() => transition(one, 'offer'), /Not authorized/);
  await assert.rejects(() => db.query("update public.shift_applications set status='accepted' where id=$1", [one]), /permission denied/);
  assert.equal((await db.query('select * from public.shift_locations where shift_id=$1', [shift])).rows.length, 0);
  await actor(workerTwoId);
  const two = await apply(shift);
  assert.equal((await db.query('select * from public.shift_applications where shift_id=$1', [shift])).rows.length, 1);
  await assert.rejects(() => transition(one, 'withdraw'), /Not authorized/);
  await assert.rejects(() => contact(one), /Not authorized/);
  await actor(employerUserId);
  await assert.rejects(() => apply(shift), /Cannot apply to own workspace/);
  assert.equal((await db.query('select * from public.shift_applications where shift_id=$1', [shift])).rows.length, 2, 'Applications do not reserve the one place.');
  assert.equal(await transition(one, 'offer'), 'offered');
  assert.equal(await transition(one, 'offer'), 'offered');
  assert.deepEqual(await contact(one), []);
  await assert.rejects(() => transition(two, 'offer'), /No offer capacity/);
  await actor(workerOneId);
  assert.equal(await transition(one, 'accept'), 'accepted');
  assert.equal(await transition(one, 'accept'), 'accepted');
  assert.deepEqual(await contact(one), [{ phone: '+38267111111', exact_address: 'Private road 42' }]);
  await actor(employerUserId);
  assert.equal((await contact(one))[0].phone, '+38267222222');
  assert.equal((await db.query('select * from public.shift_assignments where shift_id=$1', [shift])).rows.length, 0);

  const overlapping = await publish();
  await actor(workerOneId);
  const overlapApplication = await apply(overlapping);
  await actor(employerUserId);
  await transition(overlapApplication, 'offer');
  await actor(workerOneId);
  await assert.rejects(() => transition(overlapApplication, 'accept'), /Overlapping commitment/);
  assert.equal(await transition(one, 'withdraw'), 'withdrawn');
  assert.deepEqual(await contact(one), []);
  await actor(employerUserId);
  assert.equal(await transition(two, 'offer'), 'offered');
  await actor(workerTwoId);
  assert.equal(await transition(two, 'decline'), 'declined');
  await actor(workerThreeId);
  const three = await apply(shift);
  await actor(employerUserId);
  assert.equal(await transition(three, 'offer'), 'offered');
  await actor(employerUserId, 'owner');
  await db.query("update public.shift_applications set offer_expires_at=now()-interval '1 second' where id=$1", [three]);
  await actor(workerThreeId);
  assert.equal((await db.query('select effective_status from public.application_inbox where id=$1', [three])).rows[0].effective_status, 'expired');
  assert.equal(await transition(three, 'accept'), 'expired');
  assert.deepEqual(await contact(three), []);
  await actor(workerOneId);
  await transition(overlapApplication, 'accept');
  await actor(employerUserId);
  await db.query('select public.cancel_application_post($1)', [overlapping]);
  await db.query('select public.cancel_application_post($1)', [overlapping]);
  await actor(workerOneId);
  assert.deepEqual(await contact(overlapApplication), []);
  assert.equal((await db.query('select effective_status from public.application_inbox where id=$1', [overlapApplication])).rows[0].effective_status, 'cancelled');
  await actor(null, 'anon');
  assert.equal((await db.query('select * from public.public_shift_listings where shift_id=$1', [overlapping])).rows.length, 0);
  await actor(employerUserId, 'owner');
  assert.equal((await db.query("select count(*)::int as n from private.application_events where application_id=$1 and event='accepted'", [one])).rows[0].n, 1, 'Retries must not duplicate transition events.');
  await actor(employerUserId);
  const expiryShift = await publish();
  await actor(workerOneId);
  const expiring = await apply(expiryShift);
  await actor(workerTwoId);
  const replacement = await apply(expiryShift);
  await actor(employerUserId);
  await transition(expiring, 'offer');
  await actor(employerUserId, 'owner');
  await db.query("update public.shift_applications set offer_expires_at=now()-interval '1 second' where id=$1", [expiring]);
  await actor(employerUserId);
  assert.equal(await transition(expiring, 'offer'), 'expired', 'Offer retries cannot revive expired holds.');
  assert.equal(await transition(replacement, 'offer'), 'offered', 'Expired offers release capacity without cron.');
  assert.equal(await transition(replacement, 'revoke'), 'cancelled');
  await actor(workerThreeId);
  const rejected = await apply(expiryShift);
  await actor(employerUserId);
  assert.equal(await transition(rejected, 'reject'), 'rejected');
  await assert.rejects(() => transition(rejected, 'offer'), /Invalid application state/);
  const delayedShift = await publish();
  await actor(workerOneId);
  const delayed = await apply(delayedShift);
  await actor(employerUserId);
  await transition(delayed, 'offer');
  await actor(employerUserId, 'owner');
  await db.exec('begin');
  await db.query("update public.shift_applications set offer_expires_at=clock_timestamp()+interval '20 milliseconds' where id=$1", [delayed]);
  await actor(workerOneId);
  await new Promise((resolve) => setTimeout(resolve, 60));
  assert.equal(await transition(delayed, 'accept'), 'expired', 'A transaction begun before expiry cannot accept after the actual deadline.');
  await db.exec('rollback');
  await actor(employerUserId, 'owner');
  await db.exec('begin');
  await db.query('delete from public.employer_members where employer_id=$1 and user_id=$2', [employerId, employerUserId]);
  await actor(employerUserId);
  await db.exec('savepoint denied_contact');
  await assert.rejects(() => contact(one), /Not authorized/);
  await db.exec('rollback to savepoint denied_contact');
  await assert.rejects(() => db.query('select public.cancel_application_post($1)', [expiryShift]), /Not authorized/);
  await db.exec('rollback');
  console.log('Phase 3: pilot gate, publish retry, privacy, apply, capacity, offers, acceptance, overlap, withdrawal, decline, expiry and cancellation verified');
}
