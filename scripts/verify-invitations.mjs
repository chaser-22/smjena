import assert from 'node:assert/strict';

// Disposable PGlite only. Never use these fixtures on a hosted project.
export async function verifyInvitations(db, { employerId, employerUserId, workerOneId, workerTwoId }) {
  const actor = async (id, role = 'authenticated') => {
    await db.exec('reset role');
    await db.query("select set_config('request.jwt.claim.sub',$1,false)", [id ?? '']);
    if (role !== 'operator') await db.exec(`set role ${role}`);
  };
  const publish = async () => {
    await actor(employerUserId);
    return (await db.query(`select public.publish_application_shift($1,gen_random_uuid(),'Invitation test hotel','Konobar','Centar','Private invitation location',now()+interval '60 days',now()+interval '60 days 6 hours',8000,1::smallint,'{}'::text[],true) id`, [employerId])).rows[0].id;
  };
  assert.equal((await db.query('select count(*)::int n from public.application_invitations')).rows[0].n, 0);
  const beforeLegacy = (await db.query('select count(*)::int n from public.shift_assignments')).rows[0].n;
  await db.query('insert into public.trusted_workers(employer_id,worker_id) values($1,$2) on conflict do nothing', [employerId, workerOneId]);
  await actor(workerTwoId);
  await assert.rejects(() => db.query('select * from public.preferred_workers($1)', [employerId]), /Not authorized/);
  await assert.rejects(() => db.query('select public.set_preferred_worker($1,$2,true)', [employerId, workerTwoId]), /Not authorized/);
  const shift = await publish();
  const preferred = (await db.query('select * from public.preferred_workers($1)', [employerId])).rows;
  assert.ok(preferred.some(row => row.worker_id === workerOneId));
  assert.deepEqual(Object.keys(preferred[0]).sort(), ['worker_id', 'worker_name']);
  const invite = (await db.query('select public.invite_preferred_worker($1,$2) id', [shift, workerOneId])).rows[0].id;
  assert.equal((await db.query('select public.invite_preferred_worker($1,$2) id', [shift, workerOneId])).rows[0].id, invite);
  assert.equal((await db.query('select count(*)::int n from public.shift_applications where shift_id=$1', [shift])).rows[0].n, 0, 'Invitations never auto-apply or reserve places.');
  await actor(workerOneId);
  assert.equal((await db.query('select effective_status from public.application_invitation_inbox where id=$1', [invite])).rows[0].effective_status, 'invited');
  assert.equal((await db.query('select shift_id from public.application_posts where shift_id=$1', [shift])).rows.length, 1);
  assert.equal((await db.query('select exact_address from public.shift_locations where shift_id=$1', [shift])).rows.length, 0, 'Invitation does not disclose private location.');
  assert.equal((await db.query("select id from public.marketplace_notifications where shift_id=$1 and kind='invited'", [shift])).rows.length, 1);
  await assert.rejects(() => db.query('select * from public.application_contact($1)', [invite]), /Not authorized/);
  await assert.rejects(() => db.query('insert into public.application_invitations(shift_id,worker_id,worker_name) values($1,$2,\'Forged\')', [shift, workerOneId]), /permission denied/);
  await actor(workerTwoId);
  assert.equal((await db.query('select id from public.application_invitations where id=$1', [invite])).rows.length, 0);
  assert.equal((await db.query('select shift_id from public.application_posts where shift_id=$1', [shift])).rows.length, 0);
  await assert.rejects(() => db.query('select public.dismiss_application_invitation($1)', [invite]), /Not authorized/);
  await actor(workerOneId);
  await db.query('select public.dismiss_application_invitation($1)', [invite]);
  await db.query('select public.dismiss_application_invitation($1)', [invite]);
  assert.equal((await db.query('select effective_status from public.application_invitation_inbox where id=$1', [invite])).rows[0].effective_status, 'dismissed');
  await actor(null, 'service_role');
  assert.equal((await db.query('select * from public.lease_application_push()')).rows.some(row => row.kind === 'invited'), false, 'Dismissed invitations must not be delivered later.');
  await assert.rejects(() => db.query('select * from private.lease_application_push_base()'), /permission denied/);
  await actor(workerOneId);
  const application = (await db.query('select public.apply_to_shift($1) id', [shift])).rows[0].id;
  assert.equal((await db.query('select effective_status from public.application_invitation_inbox where id=$1', [invite])).rows[0].effective_status, 'applied');
  assert.equal((await db.query('select * from public.application_contact($1)', [application])).rows.length, 0);
  await assert.rejects(() => db.query("select public.transition_application($1,'accept')", [application]), /Invalid application state/);
  await actor(employerUserId);
  await db.query("select public.transition_application($1,'offer')", [application]);
  await actor(workerOneId);
  await db.query("select public.transition_application($1,'accept')", [application]);
  assert.equal((await db.query('select * from public.application_contact($1)', [application])).rows.length, 1);
  await actor(employerUserId);
  await db.query('select public.set_preferred_worker($1,$2,false)', [employerId, workerOneId]);
  await assert.rejects(() => db.query('select public.set_preferred_worker($1,$2,true)', [employerId, workerOneId]), /Previous accepted shift required/);
  await actor(null, 'operator');
  await db.query("update public.application_posts set starts_at=now()-interval '8 hours',ends_at=now()-interval '2 hours' where shift_id=$1", [shift]);
  await actor(employerUserId);
  await db.query('select public.set_preferred_worker($1,$2,true)', [employerId, workerOneId]);
  await db.query('select public.set_preferred_worker($1,$2,true)', [employerId, workerOneId]);
  const next = await publish();
  await actor(workerOneId);
  await db.query('insert into public.invitation_preferences(user_id,allow_invitations) values($1,false)', [workerOneId]);
  await actor(employerUserId);
  await assert.rejects(() => db.query('select public.invite_preferred_worker($1,$2)', [next, workerOneId]), /Invitation unavailable/);
  await actor(workerOneId);
  await db.query('update public.invitation_preferences set allow_invitations=true where user_id=$1', [workerOneId]);
  await actor(employerUserId);
  await db.query('select public.invite_preferred_worker($1,$2)', [next, workerOneId]);
  await actor(workerOneId);
  await db.query('update public.invitation_preferences set allow_invitations=false where user_id=$1', [workerOneId]);
  await actor(null, 'service_role');
  assert.equal((await db.query('select * from public.lease_application_push()')).rows.some(row => row.kind === 'invited'), false, 'Opt-out also suppresses invitations already queued.');
  await actor(workerOneId);
  await db.query('update public.invitation_preferences set allow_invitations=true where user_id=$1', [workerOneId]);
  await actor(employerUserId);
  await db.query('select public.cancel_application_post($1)', [next]);
  await actor(workerOneId);
  assert.equal((await db.query('select effective_status from public.application_invitation_inbox where shift_id=$1', [next])).rows[0].effective_status, 'cancelled');
  await actor(null, 'service_role');
  assert.equal((await db.query('select * from public.lease_application_push()')).rows.some(row => row.kind === 'invited'), false, 'Cancelled shifts must suppress pending invitations.');
  await actor(null, 'anon');
  await assert.rejects(() => db.query('select id from public.application_invitations'), /permission denied/);
  await assert.rejects(() => db.query('select * from public.preferred_workers($1)', [employerId]), /permission denied/);
  await actor(null, 'operator');
  await db.query("insert into public.employer_members(employer_id,user_id,member_role) values($1,$2,'manager')", [employerId, workerTwoId]);
  await actor(workerTwoId);
  assert.equal((await db.query('select id from public.application_invitations where id=$1', [invite])).rows.length, 1);
  await actor(null, 'operator');
  await db.query('delete from public.employer_members where employer_id=$1 and user_id=$2', [employerId, workerTwoId]);
  await actor(workerTwoId);
  assert.equal((await db.query('select id from public.application_invitations where id=$1', [invite])).rows.length, 0, 'Former firm members lose access.');
  await assert.rejects(() => db.query('select public.invite_preferred_worker($1,$2)', [next, workerOneId]), /Not authorized/);
  await actor(null, 'operator');
  // Advance only the independent publishing-limit fixtures, not invitation time.
  await db.exec("update public.application_posts set created_at=now()-interval '2 days'");
  let lastShift;
  for (let index=0; index<8; index++) {
    lastShift=await publish();
    await db.query('select public.invite_preferred_worker($1,$2)', [lastShift, workerOneId]);
  }
  const overLimit=await publish();
  await assert.rejects(() => db.query('select public.invite_preferred_worker($1,$2)', [overLimit, workerOneId]), /Invitation rate limit/);
  await actor(null, 'operator');
  await db.query("update public.application_posts set starts_at=now()-interval '1 minute' where shift_id=$1", [lastShift]);
  await actor(workerOneId);
  assert.equal((await db.query('select effective_status from public.application_invitation_inbox where shift_id=$1', [lastShift])).rows[0].effective_status, 'expired');
  await actor(null, 'operator');
  assert.equal((await db.query('select count(*)::int n from public.shift_assignments')).rows[0].n, beforeLegacy);
  console.log('Invitations: no auto-application/reservation/contact, preference opt-out, idempotency, recipient RLS, consent lifecycle and stale push suppression verified');
}
